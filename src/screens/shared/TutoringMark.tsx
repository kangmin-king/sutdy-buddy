/**
 * 과외 날(수업일) 표시 — 날짜 원 **위**에 놓이는 짧은 막대.
 *
 * 예전엔 날짜 원을 `bg-tertiary-container/40`으로 채웠는데, 배경 대비가 라이트 1.46:1,
 * 다크 1.20:1이라 사실상 안 보였다(비-텍스트 요소 기준은 3:1). 다크에서 특히 심했다.
 *
 * 면을 진하게 하는 것으로는 못 고친다 — 채운 원은 이미 "선택된 날"이 쓰는 채널이라,
 * 과외 날을 3:1까지 올리면 선택과 무게가 비슷해져 둘이 섞인다. 바깥 링은 이행률이,
 * 날짜 아래 마커 줄은 시험·숙제가, 1px 테두리는 오늘이 쓰고 있다. 그래서 아직 아무도
 * 안 쓰는 채널인 **원 위쪽 공간**으로 옮겼다. 색이 아니라 위치로 구분되므로 색약
 * 사용자에게도 읽히고, 다른 여섯 상태와 겹쳐도 서로를 가리지 않는다.
 *
 * 색은 `on-surface-variant`다(라이트 8.86:1 / 다크 7.31:1). 날짜 글자(`on-surface`,
 * 14~16:1)보다 한 단계 약하게 둔 것은 의도다 — 과외 날은 그 날의 성질이지 날짜 자체보다
 * 중요한 정보가 아니다.
 *
 * `active`가 false여도 자리는 그대로 차지한다. 안 그러면 과외 날이 있는 주와 없는 주의
 * 행 높이가 달라져 날짜가 세로로 어긋난다.
 *
 * 달력 칸에서는 `className="mb-[3px]"`로 원과의 간격을 준다. 범례에서는 글자와 가로로
 * 나란히 놓이므로 그 여백이 없어야 한다 — 그래서 여백을 컴포넌트 밖으로 뺐다.
 */
export function TutoringMark({ active, className = '' }: { active: boolean; className?: string }) {
  return (
    <span
      aria-hidden="true"
      className={`h-[3px] w-4 shrink-0 rounded-full ${active ? 'bg-on-surface-variant' : 'bg-transparent'} ${className}`}
    />
  );
}
